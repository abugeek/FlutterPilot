// Generates the agent-facing guidance the server ships, from `guidance/`:
//
//   guidance/instructions.md  -> lib/src/generated/guidance.g.dart (serverInstructions)
//   guidance/guide.md         -> lib/src/generated/guidance.g.dart (guidePrompt)
//   guidance/skill.md         -> skills/flutterpilot/SKILL.md
//
// One source per text, so a sentence is fixed once. A marker on its own,
// `<!-- include: name -->`, is replaced by `guidance/partials/name.md`
// (one level: a partial may not include another). Run from the package root:
//
//   dart run tool/generate_guidance.dart
//
// `test/guidance_generated_test.dart` runs the same code in memory and fails
// when a generated file is out of date. Each const is the file body wrapped in
// `'''` with one leading and one trailing newline; SKILL.md gets the
// "generated" note after its frontmatter (frontmatter must stay first).
import 'dart:io';

const _skillPath = 'skills/flutterpilot/SKILL.md';

const _skillNote =
    '<!-- Generated by tool/generate_guidance.dart from guidance/skill.md; '
    'do not edit. -->';

final _include = RegExp(r'<!--\s*include:\s*([a-z0-9-]+)\s*-->');

String _read(File file) => file.readAsStringSync().replaceAll('\r\n', '\n');

/// The `lib/src/generated/guidance.g.dart` the package should have.
String renderGuidanceDart(Directory packageRoot) {
  final guidance = Directory('${packageRoot.path}/guidance');
  final partials = loadPartials(guidance);
  final instructions = expandIncludes(
    _read(File('${guidance.path}/instructions.md')),
    partials,
  );
  final guide = expandIncludes(
    _read(File('${guidance.path}/guide.md')),
    partials,
  );
  return '''
// Generated by tool/generate_guidance.dart from guidance/, do not edit.
library;

/// Sent once when a client connects, and the only FlutterPilot text an
/// agent has before it reads a tool (clients that load tool schemas on
/// demand keep this in context instead): how to start and what not to
/// repeat. What a single tool does belongs in its description.
const serverInstructions = \'\'\'
${escape(instructions.trimRight())}\'\'\';

/// The body of the `flutterpilot_guide` prompt, from guidance/guide.md.
const guidePrompt = \'\'\'
${escape(guide.trimRight())}\'\'\';
''';
}

/// The `skills/flutterpilot/SKILL.md` the repo should have.
String renderSkill(Directory packageRoot) {
  final guidance = Directory('${packageRoot.path}/guidance');
  final body = expandIncludes(
    _read(File('${guidance.path}/skill.md')),
    loadPartials(guidance),
  );
  if (!body.startsWith('---\n')) {
    throw StateError('guidance/skill.md must start with its YAML frontmatter.');
  }
  final end = body.indexOf('\n---', 3);
  if (end < 0) {
    throw StateError('guidance/skill.md frontmatter is not closed.');
  }
  final after = body.indexOf('\n', end + 1) + 1;
  return '${body.substring(0, after)}\n$_skillNote\n${body.substring(after)}';
}

/// Replaces every `<!-- include: name -->` with `partials/name.md`.
String expandIncludes(String text, Map<String, String> partials) =>
    text.replaceAllMapped(_include, (match) {
      final name = match[1]!;
      final partial = partials[name];
      if (partial == null) {
        throw StateError(
          'guidance/partials/$name.md is missing (referenced as ${match[0]}).',
        );
      }
      return partial;
    });

/// `guidance/partials/*.md`, by name without the extension.
Map<String, String> loadPartials(Directory guidance) {
  final dir = Directory('${guidance.path}/partials');
  if (!dir.existsSync()) return const {};
  final partials = <String, String>{};
  for (final file in dir.listSync().whereType<File>()) {
    if (!file.path.endsWith('.md')) continue;
    final name = file.uri.pathSegments.last.substring(
      0,
      file.uri.pathSegments.last.length - 3,
    );
    final body = _read(file).trimRight();
    if (_include.hasMatch(body)) {
      throw StateError(
        'guidance/partials/$name.md includes another partial: one level only.',
      );
    }
    partials[name] = body;
  }
  return partials;
}

/// Escapes what would end the Dart `'''` literal or interpolate.
String escape(String text) => text
    .replaceAll(r'\', r'\\')
    .replaceAll(r'$', r'\$')
    .replaceAll("'''", r"\'\'\'");

void main() {
  final packageRoot = Directory.current;
  final repoRoot = packageRoot.parent.parent;
  final dartFile = File('${packageRoot.path}/lib/src/generated/guidance.g.dart')
    ..createSync(recursive: true);
  dartFile.writeAsStringSync(renderGuidanceDart(packageRoot));
  File('${repoRoot.path}/$_skillPath')
    ..createSync(recursive: true)
    ..writeAsStringSync(renderSkill(packageRoot));
  stdout.writeln(
    'Generated lib/src/generated/guidance.g.dart and $_skillPath '
    'from guidance/.',
  );
}
