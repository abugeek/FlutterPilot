import 'dart:io';

/// The Dart file under [lib] that declares `class [name]`, or null.
File? findClassFile(Directory lib, String name) {
  if (!lib.existsSync()) return null;
  final declares = RegExp(
    '^\\s*(?:abstract\\s+|final\\s+|base\\s+)*class\\s+$name\\b',
    multiLine: true,
  );
  for (final f in lib.listSync(recursive: true).whereType<File>()) {
    if (f.path.endsWith('.dart') && declares.hasMatch(f.readAsStringSync())) {
      return f;
    }
  }
  return null;
}

/// A widget test that pumps [widget] (imported from [import]) at each of
/// [viewports] (logical width, height) and matches it against
/// `goldens/<name>_<viewport>.png` next to the test.
String goldenTestSource({
  required String name,
  required String import,
  required String widget,
  required Map<String, (int, int)> viewports,
  bool riverpod = false,
}) {
  final app = 'MaterialApp(debugShowCheckedModeBanner: false, home: $widget)';
  final buf = StringBuffer()
    ..writeln('// Generated by FlutterPilot (synthesize_golden_test).')
    ..writeln(
      '// Update the images: flutter test test/${name}_golden_test.dart '
      '--update-goldens',
    )
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln("import 'package:flutter_test/flutter_test.dart';");
  if (riverpod) {
    buf.writeln("import 'package:flutter_riverpod/flutter_riverpod.dart';");
  }
  buf
    ..writeln("import '$import';")
    ..writeln()
    ..writeln('void main() {');
  for (final MapEntry(key: label, value: (w, h)) in viewports.entries) {
    buf
      ..writeln("  testWidgets('$name on $label', (tester) async {")
      ..writeln('    tester.view.devicePixelRatio = 1;')
      ..writeln('    tester.view.physicalSize = const Size($w, $h);')
      ..writeln('    addTearDown(tester.view.reset);')
      ..writeln(
        '    await tester.pumpWidget(${riverpod ? 'ProviderScope(child: $app)' : app});',
      )
      // A spinner never settles: pump a fixed second instead.
      ..writeln('    await tester.pump(const Duration(seconds: 1));')
      ..writeln('    await expectLater(')
      ..writeln('      find.byType(MaterialApp),')
      ..writeln("      matchesGoldenFile('goldens/${name}_$label.png'),")
      ..writeln('    );')
      ..writeln('  });');
  }
  buf.writeln('}');
  return buf.toString();
}
